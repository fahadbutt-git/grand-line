# shellcheck shell=bash
# System settings: keyboard, files, screenshots and clipboard history.

# defaults_array_items DOMAIN KEY: print the array's items, one per line
# (nothing when the key is not set).
defaults_array_items() {
  defaults read "$1" "$2" 2>/dev/null | sed -e '1d' -e '$d' -e 's/^[[:space:]]*//' -e 's/,$//' -e 's/^"\(.*\)"$/\1/'
}

# defaults_array_ensure DOMAIN KEY START -- ITEM...: make sure the array holds
# every ITEM, keeping what is there (yours included). START is a
# comma-separated list used when the key is not set yet (the app's own
# defaults, which writing the key would otherwise replace).
defaults_array_ensure() {
  local domain="$1" key="$2" start="$3" have item missing=0 all=()
  shift 4
  have="$(defaults_array_items "$domain" "$key")"
  if [[ -n "$have" ]]; then
    while IFS= read -r item; do all+=("$item"); done <<<"$have"
  elif [[ -n "$start" ]]; then
    IFS=',' read -r -a all <<<"$start"
    missing=1
  fi
  for item in "$@"; do
    if ! printf '%s\n' "${all[@]+"${all[@]}"}" | grep -qxF -- "$item"; then
      all+=("$item"); missing=1
    fi
  done
  [[ "$missing" == 1 ]] || return 0
  run defaults write "$domain" "$key" -array "${all[@]}"
}

# Clipboard history never keeps what is copied in the clinical remote app
# (Horizon), so patient information stays out of it. Checked on every
# run, so an app added later (or a list reset by Maccy) is covered, and your
# own additions are kept. Maccy matches apps by bundle ID only: it cannot
# ignore one browser window by its title, so the web version of Horizon is
# not covered (the checklist says so). Items marked concealed or
# transient (password managers) are never kept either.
maccy_ignore_list() {
  defaults_array_ensure org.p0deje.Maccy ignoredApps "" -- \
    com.vmware.horizon com.omnissa.horizon.client.mac
  defaults_array_ensure org.p0deje.Maccy ignoredPasteboardTypes \
    "Pasteboard generator type,com.agilebits.onepassword,com.typeit4me.clipping,de.petermaurer.TransientPasteboardType,net.antelle.keeweb" -- \
    org.nspasteboard.ConcealedType org.nspasteboard.TransientType org.nspasteboard.AutoGeneratedType
}

# Control + 1 to 9 switches to desktop 1 to 9 (Caps + 1 to 9 sends these).
# macOS has the shortcuts but leaves them off; this turns on only those nine
# (ids 118 to 126), once, so a change you make later in System Settings,
# Keyboard, Keyboard Shortcuts, Mission Control is kept. Their own run flag,
# so a Mac set up before them gets them on its next update.
desktop_switch_keys() {
  first_time desktop-keys || return 0
  local n id codes=(18 19 20 21 23 22 26 28 25)
  for n in 1 2 3 4 5 6 7 8 9; do
    id=$((117 + n))
    run defaults write com.apple.symbolichotkeys AppleSymbolicHotKeys -dict-add "$id" \
      "<dict><key>enabled</key><true/><key>value</key><dict><key>parameters</key><array><integer>65535</integer><integer>${codes[n-1]}</integer><integer>262144</integer></array><key>type</key><string>standard</string></dict></dict>"
  done
  # Applies them now rather than at the next login.
  local apply=/System/Library/PrivateFrameworks/SystemAdministration.framework/Resources/activateSettings
  if [[ "$DRY_RUN" == 1 || -x "$apply" ]]; then run "$apply" -u || true; fi
  mark_done desktop-keys
}

step_macos_defaults() {
  maccy_ignore_list
  desktop_switch_keys
  if ! first_time macos-defaults; then
    ok "System settings were set on the first run (yours are kept)"
    return 0
  fi
  # Only how things behave: macOS keeps its own look (Dock, animations,
  # desktop, window tiling, Finder views and hot corners are left as they are).

  # Keyboard: fast key repeat, no accent pop-up when holding a key
  run defaults write NSGlobalDomain KeyRepeat -int 2
  run defaults write NSGlobalDomain InitialKeyRepeat -int 15
  run defaults write NSGlobalDomain ApplePressAndHoldEnabled -bool false

  # Files: show extensions, save locally by default, expanded save dialogs
  run defaults write NSGlobalDomain AppleShowAllExtensions -bool true
  run defaults write NSGlobalDomain NSDocumentSaveNewDocumentsToCloud -bool false
  run defaults write NSGlobalDomain NSNavPanelExpandedStateForSaveMode -bool true
  run defaults write NSGlobalDomain NSNavPanelExpandedStateForSaveMode2 -bool true

  # Finder: folders first, search this folder, no warning on changing an extension
  run defaults write com.apple.finder _FXSortFoldersFirst -bool true
  run defaults write com.apple.finder FXDefaultSearchScope -string SCcf
  run defaults write com.apple.finder FXEnableExtensionChangeWarning -bool false
  run defaults write com.apple.desktopservices DSDontWriteNetworkStores -bool true

  # Screenshots into their own folder
  run defaults write com.apple.screencapture location -string "$SCREENSHOTS_DIR"
  run defaults write com.apple.screencapture type -string png

  # Keyboard first, as in Omarchy: Tab moves through every control in dialogs
  run defaults write NSGlobalDomain AppleKeyboardUIMode -int 3

  # Time Machine does not ask about every new disk, no .DS_Store on USB drives
  run defaults write com.apple.TimeMachine DoNotOfferNewDisksForBackup -bool true
  run defaults write com.apple.desktopservices DSDontWriteUSBStores -bool true

  run defaults write org.p0deje.Maccy historySize -int 300

  run_sh "killall Finder SystemUIServer 2>/dev/null || true"
  mark_done macos-defaults
  ok "System settings applied"
}
